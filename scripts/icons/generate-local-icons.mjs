import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const projectRoot = process.cwd();
const sourceRoot = join(projectRoot, "src");
const outputPath = join(sourceRoot, "generated", "local-icon-collections.ts");
const sourceExtensions = new Set([
	".astro",
	".md",
	".mdx",
	".svelte",
	".ts",
	".tsx",
]);
const iconPattern = /\b(?<prefix>[a-z][a-z0-9-]*):(?<name>[a-z0-9-]+)\b/g;
const iconPrefixes = new Set([
	"fa6-brands",
	"fa6-regular",
	"fa6-solid",
	"material-symbols",
	"simple-icons",
]);

function collectSourceFiles(directory) {
	const files = [];
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const absolute = join(directory, entry.name);
		if (entry.isDirectory()) {
			if (entry.name !== "generated")
				files.push(...collectSourceFiles(absolute));
		} else if (sourceExtensions.has(extname(entry.name))) {
			files.push(absolute);
		}
	}
	return files;
}

const requested = new Map();
for (const file of collectSourceFiles(sourceRoot)) {
	const source = readFileSync(file, "utf8");
	for (const match of source.matchAll(iconPattern)) {
		const { prefix, name } = match.groups;
		if (!iconPrefixes.has(prefix) || name === "xxx") continue;
		if (!requested.has(prefix)) requested.set(prefix, new Set());
		requested.get(prefix).add(name);
	}
}

const collections = [];
for (const [prefix, names] of [...requested].sort(([a], [b]) =>
	a.localeCompare(b),
)) {
	const iconSetPath = join(
		projectRoot,
		"node_modules",
		"@iconify-json",
		prefix,
		"icons.json",
	);
	if (!existsSync(iconSetPath)) {
		throw new Error(
			`[local-icons] Missing installed icon set @iconify-json/${prefix} for ${
				[...names][0]
			}`,
		);
	}
	const source = JSON.parse(readFileSync(iconSetPath, "utf8"));
	const icons = {};
	const aliases = {};

	function include(name, chain = []) {
		if (icons[name] || aliases[name]) return;
		if (source.icons?.[name]) {
			icons[name] = source.icons[name];
			return;
		}
		const alias = source.aliases?.[name];
		if (!alias) {
			throw new Error(
				`[local-icons] Unknown icon ${prefix}:${name} referenced from src`,
			);
		}
		if (chain.includes(name)) {
			throw new Error(
				`[local-icons] Circular alias ${prefix}:${[...chain, name].join(" -> ")}`,
			);
		}
		aliases[name] = alias;
		include(alias.parent, [...chain, name]);
	}

	for (const name of [...names].sort()) include(name);
	collections.push({
		prefix,
		...(source.width ? { width: source.width } : {}),
		...(source.height ? { height: source.height } : {}),
		icons,
		...(Object.keys(aliases).length ? { aliases } : {}),
	});
}

const output = `// Generated by scripts/icons/generate-local-icons.mjs. Do not edit.\nexport const localIconCollections = ${JSON.stringify(collections)} as const;\n`;
// Avoid replacing an existing file, which can fail with EPERM on Windows.
const unchanged =
	existsSync(outputPath) && readFileSync(outputPath, "utf8") === output;
if (!unchanged) writeFileSync(outputPath, output, "utf8");

const count = collections.reduce(
	(total, collection) =>
		total +
		Object.keys(collection.icons).length +
		Object.keys(collection.aliases ?? {}).length,
	0,
);
console.log(
	`[local-icons] ${unchanged ? "Reused" : "Wrote"} ${count} icons from ${collections.length} collections to ${relative(projectRoot, outputPath)}`,
);
